import type { Display } from "./display.ts"

const MEMORY_START = 0x0200

export class CPU {
  private memory = new Uint8Array()
  private pc = MEMORY_START
  private registers = new Uint8Array()
  private i_index = 0x0
  private stack = new Uint16Array()

  public fetch() {
    // be ready to fetch the next opcode
    this.pc += 2

    return this.memory[this.pc]
  }

  // 2-byte opcode
  public decode(opcode: number, display: Display) {
    const command = (opcode >> 12) & 0xf
    const x = (opcode >> 8) & 0xf
    const y = (opcode >> 4) & 0xf
    const n = opcode & 0xf
    const nn = opcode & 0xff
    const nnn = opcode & 0xfff

    switch (opcode) {
      case 0x00e0:
        display.clear()
        break
      case 0x1000 + nnn:
        this.pc = nnn
        break
    }
  }
}

